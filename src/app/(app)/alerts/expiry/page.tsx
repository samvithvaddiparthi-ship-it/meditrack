import type { Metadata } from "next";
import { requirePageAccess } from "@/server/auth/session";
import { expiryAlerts, type ExpiryAlert } from "@/server/services/inventory.service";
import { formatDate } from "@/lib/dates";
import { can } from "@/lib/permissions";
import { formatCurrency, formatNumber } from "@/lib/format";
import { ButtonLink, Card, CardHeader, EmptyState, PageHeader, StatCard, Table, TBody, Td, TextLink, Th } from "@/components/ui/primitives";
import { FilterBar, FilterSelect, intParam, type SearchParams } from "@/components/ui/list";
import { Badge, daysLabel } from "@/components/ui/status-exports";

export const metadata: Metadata = { title: "Expiry alerts" };

function AlertTable({ rows, expired, financial, canWaste }: { rows: ExpiryAlert[]; expired: boolean; financial: boolean; canWaste: boolean }) {
  return (
    <Table caption={expired ? "Expired batches" : "Batches expiring soon"}>
      <thead>
        <tr>
          <Th>Medicine</Th>
          <Th>Batch</Th>
          <Th>Expiry</Th>
          <Th align="right">{expired ? "Days since expiry" : "Days remaining"}</Th>
          <Th align="right">Quantity</Th>
          {financial ? <Th align="right">Value</Th> : null}
          <Th>Supplier</Th>
          <Th>Action</Th>
        </tr>
      </thead>
      <TBody>
        {rows.map((r) => (
          <tr key={r.batchId}>
            <Td>
              <TextLink href={`/medicines/${r.medicineId}`}>
                {r.medicineName} {r.strength}
              </TextLink>
              <div className="text-xs text-slate-500">{r.categoryName}</div>
            </Td>
            <Td>
              <TextLink href={`/batches/${r.batchId}`} className="font-mono text-xs">
                {r.batchNumber}
              </TextLink>
            </Td>
            <Td className="whitespace-nowrap">{formatDate(r.expiryDate)}</Td>
            <Td align="right">
              <Badge tone={expired ? "danger" : r.daysToExpiry <= 7 ? "danger" : "warning"}>{expired ? `${Math.abs(r.daysToExpiry)} days ago` : daysLabel(r.daysToExpiry)}</Badge>
            </Td>
            <Td align="right" className="font-medium text-slate-900">
              {formatNumber(r.quantity)} <span className="text-xs font-normal text-slate-500">{r.unit}</span>
            </Td>
            {financial ? <Td align="right">{formatCurrency(r.stockValue)}</Td> : null}
            <Td className="text-xs">{r.supplierName ?? "—"}</Td>
            <Td>
              {expired ? (
                canWaste ? (
                  <TextLink href={`/stock/waste?batch=${r.batchId}`}>Write off as waste</TextLink>
                ) : (
                  <span className="text-xs text-slate-500">Quarantine; do not issue</span>
                )
              ) : (
                <span className="text-xs text-slate-600">Issue first (FEFO) or return to supplier</span>
              )}
            </Td>
          </tr>
        ))}
      </TBody>
    </Table>
  );
}

export default async function ExpiryAlertsPage({ searchParams }: { searchParams: Promise<SearchParams> }) {
  const user = await requirePageAccess("alerts:view");
  const params = await searchParams;
  const data = await expiryAlerts(user, intParam(params.days));
  const financial = can(user.role, "reports:financial");
  const canWaste = can(user.role, "stock:waste");
  const sum = (rows: ExpiryAlert[]) => rows.reduce((s, r) => s + r.quantity, 0);

  return (
    <>
      <PageHeader
        title="Expiry alerts"
        description={
          <>
            Generated by the stored procedure <code className="rounded bg-slate-100 px-1">CALL sp_expiring_batches({data.windowDays})</code>. A batch is expired on and after its expiry date and can only leave stock as waste.
          </>
        }
        actions={
          can(user.role, "stock:write-off-expired") && data.expired.length > 0 ? (
            <ButtonLink href="/stock/waste" variant="danger">
              Write off expired stock
            </ButtonLink>
          ) : null
        }
      />
      <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">
        <StatCard label="Expired batches" value={data.expired.length} tone="danger" hint={`${formatNumber(sum(data.expired))} units to write off`} />
        <StatCard label="Expiring soon" value={data.expiringSoon.length} tone="warning" hint={`${formatNumber(sum(data.expiringSoon))} units within ${data.windowDays} days`} />
      </div>
      <Card className="mt-6">
        <FilterBar resetHref="/alerts/expiry">
          <FilterSelect
            label="Alert window"
            name="days"
            defaultValue={String(data.windowDays)}
            options={[7, 15, 30, 60, 90, 180].map((d) => ({ value: String(d), label: `${d} days` }))}
          />
        </FilterBar>
      </Card>
      <Card className="mt-6">
        <CardHeader title={`Expired batches (${data.expired.length})`} description="Still holding stock. Ordinary issues from these batches are blocked by the database trigger." />
        {data.expired.length === 0 ? <EmptyState title="No expired stock" description="Every batch with stock is within its shelf life." /> : <AlertTable rows={data.expired} expired financial={financial} canWaste={canWaste} />}
      </Card>
      <Card className="mt-6">
        <CardHeader title={`Expiring within ${data.windowDays} days (${data.expiringSoon.length})`} description="FEFO issues these batches first." />
        {data.expiringSoon.length === 0 ? <EmptyState title={`Nothing expires in the next ${data.windowDays} days`} /> : <AlertTable rows={data.expiringSoon} expired={false} financial={financial} canWaste={canWaste} />}
      </Card>
    </>
  );
}
